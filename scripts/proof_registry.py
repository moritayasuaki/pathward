#!/usr/bin/env python3
"""Build a deterministic theorem/axiom inventory from checked Lean output."""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PROOFS = ROOT / "proofs"


def declarations():
    entries = []
    for path in sorted(PROOFS.glob("*Proofs.lean")):
        source = path.read_text()
        namespaces = set(re.findall(r"^namespace (\w+)$", source, re.M))
        if namespaces != {path.stem}:
            raise SystemExit(f"Review namespace discovery for {path.name}")
        for match in re.finditer(r"^(?:@\[[^\]]*\]\s*)*(?:theorem|lemma) (\w+)\b", source, re.M):
            end = source.find(":=", match.end())
            if end < 0:
                raise SystemExit(f"Missing theorem body in {path.name}")
            entries.append({"name": path.stem + "." + match[1],
                            "source": str(path.relative_to(ROOT)),
                            "line": source.count("\n", 0, match.start()) + 1,
                            "statement": source[match.start():end].strip()})
    names = [entry["name"] for entry in entries]
    if not entries or len(names) != len(set(names)):
        raise SystemExit("Empty or duplicate theorem registry")
    return entries


def audit_source(entries):
    modules = sorted({entry["name"].split(".")[0] for entry in entries})
    return ("-- Generated by scripts/audit.py --write-registry; do not hand-edit.\n"
            + "\n".join("import " + module for module in modules) + "\n\n"
            + "\n".join("#print axioms " + entry["name"] for entry in entries) + "\n")


def registry(entries, axiom_map):
    roadmap = json.loads((PROOFS / "roadmap.json").read_text())
    names = {entry["name"] for entry in entries}
    ids = set()
    for goal in roadmap["goals"]:
        if (goal["id"] in ids or goal["status"] not in {"planned", "in_progress", "proved", "deferred"}
                or goal["priority"] not in {"P0", "P1", "P2"}
                or not goal["acceptance"] or not set(goal["theorems"]) <= names):
            raise SystemExit(f"Invalid proof roadmap entry: {goal['id']}")
        ids.add(goal["id"])
        if goal["status"] == "proved" and not goal["theorems"]:
            raise SystemExit(f"Proved goal has no theorem: {goal['id']}")
    if not set(roadmap["model_only_theorems"]) <= names:
        raise SystemExit("Unknown model-only theorem")
    modules = {entry["name"].split(".")[0] for entry in entries}
    if set(roadmap["areas"]) != modules:
        raise SystemExit("Proof area descriptions do not match modules")
    result = []
    for entry in entries:
        entry = dict(entry, axioms=sorted(axiom_map[entry["name"]]))
        entry["scope"] = "transition_model" if entry["name"] in roadmap["model_only_theorems"] else "rust_contract_or_lemma"
        result.append(entry)
    source_files = sorted([*PROOFS.glob("*Proofs.lean"), *ROOT.glob("src/*.rs"),
                           PROOFS / "Generated/Pathward.lean", ROOT / "scripts/extract.py"])
    return {"schema": 1, "lean_toolchain": (PROOFS / "lean-toolchain").read_text().strip(),
            "theorem_count": len(result),
            "axiom_free_count": sum(not entry["axioms"] for entry in result),
            "axiom_counts": {a: sum(a in entry["axioms"] for entry in result)
                             for a in sorted({a for entry in result for a in entry["axioms"]})},
            "source_sha256": {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
                              for path in source_files},
            "theorems": result}


def write_or_check(path, text, write):
    if write:
        path.write_text(text)
    elif not path.exists() or path.read_text() != text:
        raise SystemExit(f"Stale {path.relative_to(ROOT)}; run python3 scripts/audit.py --write-registry")
